function decorate() {
  const rep = $('rep');
  if (!rep || rep.hidden || rep.querySelector('.secx')) return;
  const p = window.IG && window.IG.ST && window.IG.ST.port;
  if (!p) return;
  const tot = p.sel.reduce((s, x) => s + x.w, 0) || 1, m = {};
  p.sel.forEach((x) => { m[x.b.sector] = (m[x.b.sector] || 0) + x.w / tot; });
  const list = Object.entries(m).sort((a, b) => b[1] - a[1]);
  const t = rep.querySelector('table');
  if (t) t.insertAdjacentHTML('afterend', `<div class="secx"><h3>Отрасли портфеля</h3><table><tr><th>Отрасль</th><th>Доля</th></tr>${list.map(([n, v]) => `<tr><td>${esc(n)}</td><td>${(v * 100).toFixed(0)} %</td></tr>`).join('')}</table><p class="ft">Отрасль определяется по названию эмитента и может быть неточной. Для баланса желательно не менее трёх разных отраслей и не более 40% в одной.</p></div>`);
  rep.querySelectorAll('.bx').forEach((bx) => {
    const h = bx.querySelector('h3'), nm = h && h.firstChild && h.firstChild.textContent.trim();
    const x = p.sel.find((s) => s.b.name === nm);
    if (!x) return;
    const sp = h.querySelector('span'); if (sp) sp.insertAdjacentText('beforeend', ' · ' + x.b.sector);
    h.insertAdjacentHTML('afterend', `<p class="secx"><b>Отрасль: ${esc(x.b.sector)}.</b> ${esc(NOTE[x.b.sector] || '')} Это общая характеристика отрасли, а не оценка эмитента.</p>`);
  });
}
new MutationObserver(decorate).observe(document.body, { childList: true, subtree: true });
