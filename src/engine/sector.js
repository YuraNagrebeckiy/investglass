export function sectorOf(b) {
  const sec = String(b.secid || ''), raw = String(b.name || '');
  if (/^SU\d/.test(sec) || /^ОФЗ/i.test(raw) || b.group === 'ofz') return SECTORS[0];
  const name = raw.replace(/^[a-z](?=[А-Яа-яЁё])/, '').toUpperCase();
  for (const [label, re] of RULES) if (re.test(name)) return label;
  return 'Прочее';
}
